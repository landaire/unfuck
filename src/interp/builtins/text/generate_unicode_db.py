# Writes unicode_db.rs: the character properties, simple case mappings, and
# numeric values that CPython 2.7's unicode methods and unicodedata use, for
# every BMP code unit.
#
#   python2 generate_unicode_db.py
#
# Run it with CPython 2.7 so the data is its Unicode 5.2 database. The
# properties come from the string methods themselves, so they match what
# Py_UNICODE_ISALPHA and friends return.

import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))

FLAGS = [
    ("ALPHA", lambda u: u.isalpha()),
    ("DECIMAL", lambda u: u.isdecimal()),
    ("DIGIT", lambda u: u.isdigit()),
    ("NUMERIC", lambda u: u.isnumeric()),
    ("LOWER", lambda u: u.islower()),
    ("UPPER", lambda u: u.isupper()),
    ("TITLE", lambda u: u.istitle() and not u.isupper()),
    ("SPACE", lambda u: u.isspace()),
    ("LINEBREAK", lambda u: len((u"a" + u + u"b").splitlines()) == 2),
]


def flags_of(unit):
    character = unichr(unit)
    bits = 0
    for index, (_, test) in enumerate(FLAGS):
        if test(character):
            bits |= 1 << index
    return bits


def mapping(method):
    pairs = []
    for unit in range(0x10000):
        mapped = method(unichr(unit))
        if len(mapped) == 1 and ord(mapped) < 0x10000 and ord(mapped) != unit:
            pairs.append((unit, ord(mapped)))
    return pairs


def pair_lines(pairs):
    return "".join("    (0x%04x, 0x%04x),\n" % pair for pair in pairs)


runs = []
previous = None
for unit in range(0x10000):
    bits = flags_of(unit)
    if bits != previous:
        runs.append((unit, bits))
        previous = bits

upper = mapping(lambda u: u.upper())

# Titlecase entries record every unit whose title differs from its upper,
# including units whose title is themselves (U+01C5).
title = []
for unit in range(0x10000):
    titled = unichr(unit).title()
    if len(titled) == 1 and ord(titled) < 0x10000 and titled != unichr(unit).upper():
        title.append((unit, ord(titled)))

# Numeric values of the NUMERIC units. A decimal or digit unit's value is
# its numeric value, so one table serves all three.
numeric = []
for unit in range(0x10000):
    character = unichr(unit)
    if not character.isnumeric():
        continue
    value = unicodedata.numeric(character)
    if character.isdigit():
        assert unicodedata.digit(character) == value
    if character.isdecimal():
        assert unicodedata.decimal(character) == value
    numeric.append((unit, value))

output = []
output.append("//! Character properties, simple case mappings, and numeric values of every\n")
output.append("//! BMP code unit, from the Unicode 5.2 database of CPython 2.7. Generated by\n")
output.append("//! `generate_unicode_db.py`.\n\n")
output.append("bitflags::bitflags! {\n    pub struct Properties: u16 {\n")
for index, (name, _) in enumerate(FLAGS):
    output.append("        const %s = 1 << %d;\n" % (name, index))
output.append("    }\n}\n\n")
output.append("/// Runs of equal properties as `(first unit, property bits)`, sorted.\n")
output.append("pub static PROPERTY_RUNS: &[(u16, u16)] = &[\n%s];\n\n" % pair_lines(runs))
output.append("/// Units whose simple lowercase mapping differs, sorted.\n")
output.append("pub static LOWER_MAP: &[(u16, u16)] = &[\n%s];\n\n" % pair_lines(mapping(lambda u: u.lower())))
output.append("/// Units whose simple uppercase mapping differs, sorted.\n")
output.append("pub static UPPER_MAP: &[(u16, u16)] = &[\n%s];\n\n" % pair_lines(upper))
output.append("/// Units whose titlecase mapping differs from the uppercase one, sorted.\n")
output.append("pub static TITLE_MAP: &[(u16, u16)] = &[\n%s];\n\n" % pair_lines(title))
output.append("/// Numeric values of the `NUMERIC` units, sorted. The value of a `DECIMAL`\n")
output.append("/// or `DIGIT` unit is its digit.\n")
output.append("pub static NUMERIC_VALUES: &[(u16, f64)] = &[\n%s];\n" % "".join("    (0x%04x, %r),\n" % pair for pair in numeric))

with open(os.path.join(HERE, "unicode_db.rs"), "w") as handle:
    handle.write("".join(output))

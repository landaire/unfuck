# Writes unicode_name_table.rs: the character names that the name hash of
# CPython 2.7's unicodedata module holds, and an index of them by code
# point, for unicode_names.rs.
#
#   python2 generate_unicode_names.py
#
# Run it with a UCS4 build of CPython 2.7 so the data is its Unicode 5.2
# database and unichr covers every plane. Hangul syllable and unified
# ideograph names are left out because _getcode derives them instead of
# looking them up.

import os
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))

# Digit bytes follow every byte a name can contain.
DIGIT_BASE = ord("]")
RADIX = 34
CODE_DIGITS = 4
OFFSET_DIGITS = 4
BLOCK_SIZE = 32
LINE_WIDTH = 96

ALGORITHMIC_PREFIXES = ("HANGUL SYLLABLE ", "CJK UNIFIED IDEOGRAPH-")


def digit(value):
    assert 0 <= value < RADIX
    return chr(DIGIT_BASE + value)


def number_digits(value, count):
    digits = []
    for _ in range(count):
        digits.append(digit(value % RADIX))
        value //= RADIX
    assert value == 0
    return "".join(reversed(digits))


def string_lines(data):
    return "".join('    "%s",\n' % data[start:start + LINE_WIDTH] for start in range(0, len(data), LINE_WIDTH))


def common_prefix(left, right):
    length = 0
    limit = min(len(left), len(right), RADIX - 1)
    while length < limit and left[length] == right[length]:
        length += 1
    return length


entries = []
for code in range(0x110000):
    name = unicodedata.name(unichr(code), None)
    if name is None or name.startswith(ALGORITHMIC_PREFIXES):
        continue
    assert max(ord(byte) for byte in name) < DIGIT_BASE
    entries.append((name, code))
entries.sort()

data = []
blocks = []
offsets = []
offset = 0
previous = ""
for index, (name, code) in enumerate(entries):
    if index % BLOCK_SIZE == 0:
        blocks.append(offset)
        prefix = 0
    else:
        prefix = common_prefix(previous, name)
    entry = digit(prefix) + name[prefix:] + number_digits(code, CODE_DIGITS)
    offsets.append((code, offset))
    data.append(entry)
    offset += len(entry)
    previous = name
data = "".join(data)
offsets.sort()
code_order = "".join(number_digits(offset, OFFSET_DIGITS) for _, offset in offsets)

output = []
output.append("//! Character names of the Unicode 5.2 database of CPython 2.7, as the\n")
output.append("//! name hash of `unicodedata` holds them. Hangul syllable and unified\n")
output.append("//! ideograph names are absent. Generated by `generate_unicode_names.py`.\n\n")
output.append("/// First byte of the digits in `NAMES`. Name bytes are all below it.\n")
output.append("pub const DIGIT_BASE: u8 = b'%s';\n\n" % chr(DIGIT_BASE))
output.append("pub const RADIX: u32 = %d;\n\n" % RADIX)
output.append("pub const CODE_DIGITS: usize = %d;\n\n" % CODE_DIGITS)
output.append("pub const OFFSET_DIGITS: usize = %d;\n\n" % OFFSET_DIGITS)
output.append("/// Names sorted bytewise. Each entry is one digit giving the length of the\n")
output.append("/// prefix shared with the previous name, the rest of the name, and\n")
output.append("/// `CODE_DIGITS` digits of the code point, most significant first.\n")
output.append("pub static NAMES: &str = concat!(\n%s);\n\n" % string_lines(data))
output.append("/// Offset in `NAMES` of each block of %d entries. The first entry of a\n" % BLOCK_SIZE)
output.append("/// block shares no prefix with the previous name.\n")
output.append("pub static BLOCKS: &[u32] = &[\n")
for start in range(0, len(blocks), 10):
    output.append("    %s,\n" % ", ".join(str(block) for block in blocks[start:start + 10]))
output.append("];\n\n")
output.append("/// The offset in `NAMES` of every entry as `OFFSET_DIGITS` digits, most\n")
output.append("/// significant first, in order of the entries' code points.\n")
output.append("pub static CODE_ORDER: &str = concat!(\n%s);\n" % string_lines(code_order))

with open(os.path.join(HERE, "unicode_name_table.rs"), "w") as handle:
    handle.write("".join(output))

# Writes winerror_map.rs: the errno that WindowsError(code, msg) reports for
# each Windows error code, observed by running this script under CPython
# 2.7.12 for Windows x64:
#
#   /var/mnt/build/winpy/winpy2712.sh generate_winerror_map.py
#
# Codes past LIMIT, and negative codes, all map to the default value.

import os

HERE = os.path.dirname(os.path.abspath(__file__))
LIMIT = 70000

observed = [WindowsError(code, 'x').errno for code in range(LIMIT)]
default = WindowsError(LIMIT, 'x').errno
assert all(WindowsError(code, 'x').errno == default for code in (-1, -2, 2 ** 31 - 1, LIMIT * 2))

arms = {}
start = None
for code in range(LIMIT + 1):
    value = observed[code] if code < LIMIT else default
    if start is not None and (value != current or code == LIMIT):
        if current != default:
            arms.setdefault(current, []).append((start, code - 1))
        start = None
    if start is None and code < LIMIT:
        start, current = code, value

lines = [
    "//! The errno `WindowsError` reports for a Windows error code. Generated by",
    "//! `generate_winerror_map.py` from the reference interpreter's results.",
    "",
    "pub fn winerror_to_errno(code: i32) -> i32 {",
    "    match code {",
]
for value in sorted(arms, key=lambda value: arms[value][0]):
    patterns = " | ".join(str(a) if a == b else "%d..=%d" % (a, b) for a, b in arms[value])
    lines.append("        %s => %d," % (patterns, value))
lines += ["        _ => %d," % default, "    }", "}", ""]

with open(os.path.join(HERE, "winerror_map.rs"), "wb") as output:
    output.write("\n".join(lines))

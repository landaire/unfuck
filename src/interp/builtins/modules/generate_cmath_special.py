# Writes cmath_special.rs: the results of the cmath functions for arguments
# with an infinite or NaN part, measured on the reference interpreter (the
# Windows x64 build of CPython 2.7.12). Run it with that interpreter:
#
#   python2 generate_cmath_special.py > cmath_special.rs
#
# Each part of an argument falls into one of seven categories. For every pair
# of categories with an infinite or NaN member, the script evaluates the
# function at several representative arguments. When all of them give the
# same result the cell holds that result, bit for bit (NaN signs included).
# When all of them raise ValueError the cell is marked invalid. When the
# results differ, the cell is marked signed: its parts are infinities, zeros,
# or ones whose signs follow the finite part, which the Rust code computes.

import cmath
import math
import struct
import sys

INF = float("inf")
POSITIVE_NAN = struct.unpack("<d", struct.pack("<Q", 0x7FF8000000000000))[0]
NEGATIVE_NAN = struct.unpack("<d", struct.pack("<Q", 0xFFF8000000000000))[0]

# In the order of `Category` in cmath.rs.
CATEGORIES = [
    [-INF],
    [-1e300, -3.0, -2.0, -1.0, -0.5, -1e-300, -5e-324],
    [-0.0],
    [0.0],
    [5e-324, 1e-300, 0.5, 1.0, 2.0, 3.0, 1e300],
    [INF],
    [POSITIVE_NAN, NEGATIVE_NAN],
]

# Functions whose other members follow from these by a rotation or a scale.
FUNCTIONS = [
    ("ACOS", lambda a, b: cmath.acos(complex(a, b))),
    ("ACOSH", lambda a, b: cmath.acosh(complex(a, b))),
    ("ASINH", lambda a, b: cmath.asinh(complex(a, b))),
    ("ATANH", lambda a, b: cmath.atanh(complex(a, b))),
    ("COSH", lambda a, b: cmath.cosh(complex(a, b))),
    ("EXP", lambda a, b: cmath.exp(complex(a, b))),
    ("LOG", lambda a, b: cmath.log(complex(a, b))),
    ("SINH", lambda a, b: cmath.sinh(complex(a, b))),
    ("SQRT", lambda a, b: cmath.sqrt(complex(a, b))),
    ("TANH", lambda a, b: cmath.tanh(complex(a, b))),
    ("RECT", lambda a, b: cmath.rect(a, b)),
]


def bits(value):
    return struct.unpack("<Q", struct.pack("<d", value))[0]


def evaluate(function, real, imag):
    try:
        result = function(real, imag)
    except ValueError:
        return "invalid"
    return (bits(result.real), bits(result.imag))


def cell(function, row, column):
    results = set()
    for real in CATEGORIES[row]:
        for imag in CATEGORIES[column]:
            results.add(evaluate(function, real, imag))
    if len(results) == 1:
        return results.pop()
    # Only sign differences are expected.
    magnitudes = set((r[0] & ~(1 << 63), r[1] & ~(1 << 63)) for r in results if r != "invalid")
    assert "invalid" not in results and len(magnitudes) == 1, (row, column, results)
    return "signed"


def literal(value):
    return "f64::from_bits(0x%016X)" % value


def main():
    out = sys.stdout
    out.write("//! Results of `cmath` functions for arguments with an infinite or NaN\n")
    out.write("//! part, measured on the reference interpreter. Rows follow the category\n")
    out.write("//! of the real part and columns that of the imaginary part. Generated by\n")
    out.write("//! `generate_cmath_special.py`; do not edit. Cells for two finite parts\n")
    out.write("//! are never read and hold NaN.\n")
    out.write("\n")
    out.write("use crate::interp::builtins::modules::cmath::FixedTable;\n")
    out.write("use crate::interp::builtins::modules::cmath::SpecialTable;\n")
    out.write("use crate::interp::builtins::modules::cmath::SpecialValue;\n")
    out.write("use crate::interp::complex::Complex;\n")
    for name, function in FUNCTIONS:
        # Finite arguments never consult the table; those cells hold NaN.
        finite = set(range(1, 5))
        unused = (bits(POSITIVE_NAN), bits(POSITIVE_NAN))
        cells = [[unused if row in finite and column in finite else cell(function, row, column) for column in range(7)] for row in range(7)]
        fixed = all(isinstance(c, tuple) for line in cells for c in line)
        out.write("\n")
        if fixed:
            out.write("pub(super) static %s: FixedTable = [\n" % name)
        else:
            out.write("pub(super) static %s: SpecialTable = [\n" % name)
        for line in cells:
            out.write("    [\n")
            for c in line:
                if c == "invalid":
                    out.write("        SpecialValue::Invalid,\n")
                elif c == "signed":
                    out.write("        SpecialValue::Signed,\n")
                else:
                    value = "Complex { real: %s, imag: %s }" % (literal(c[0]), literal(c[1]))
                    if fixed:
                        out.write("        %s,\n" % value)
                    else:
                        out.write("        SpecialValue::Fixed(%s),\n" % value)
            out.write("    ],\n")
        out.write("];\n")


main()

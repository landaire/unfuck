pub fn init(vm: &Vm, module: &ObjectRef) -> PyResult<()> {
    let errorcode = vm.new_dict();
    set_attribute(
        vm,
        module,
        "errorcode",
        Value::Object(Rc::clone(&errorcode)),
    )?;

    for (name, code) in CODES {
        set_attribute(vm, module, name, Value::Int(code))?;
        vm.dict_set(&errorcode, Value::Int(code), Value::str(name))?;
    }

    Ok(())
}
